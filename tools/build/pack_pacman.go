// The Arch package: one .pkg.tar.<compression> per architecture, for Arch and
// everything downstream of it. A package is a tar archive holding three files
// of metadata next to the payload: what the package is, what to run around
// installing it, and a listing of every file with its digests.

package main

import (
	"fmt"
	"os/exec"
	"path/filepath"
	"strings"
)

// pacmanCompression is the compression to pack with. The official repositories
// use zstd, xz needs a tool of that name, and the standard library writes only
// gzip. pacman reads a package through libarchive with every filter enabled and
// ignores the file name, so it takes any of the three.
func pacmanCompression() compression {
	for _, c := range []struct {
		tool string
		kind compression
	}{
		{"zstd", compressZstd},
		{"xz", compressXz},
	} {
		if _, err := exec.LookPath(c.tool); err == nil {
			return c.kind
		}
	}
	fmt.Println("  note: neither zstd nor xz is installed, packing with gzip, which pacman reads")
	return compressGzip
}

// taskPacman builds the Arch packages, one for each architecture, into
// dist/packages/. The build without the tray is the one that goes in: the
// package runs the program as a service, and a desktop uses the archive.
func taskPacman(root string) error {
	c := pacmanCompression()
	for _, t := range targets() {
		// Arch builds for two architectures: the one its own repositories carry
		// and the one of its ARM port. There is no MIPS in this family; the
		// routers have a package of their own.
		if t.tags != notrayTag || t.goarch != "amd64" && t.goarch != "arm64" {
			continue
		}
		if err := buildTarget(root, t); err != nil {
			return err
		}
		if err := packagePacman(root, t, c); err != nil {
			return err
		}
	}
	// The digests are rewritten here too, this task being registered on its own as
	// well as under taskPackages.
	return writeChecksums(root)
}

func packagePacman(root string, t target, c compression) error {
	rel, err := packageVersion(root)
	if err != nil {
		return err
	}
	repo, err := appRepo(root)
	if err != nil {
		return err
	}
	arch := pacmanArch(t.goarch)
	files, err := systemdFiles(root, filepath.Join(root, distDir, t.name()))
	if err != nil {
		return err
	}
	// Arch names the members of a package relative to the root of the target, so
	// the shared file list loses its leading slashes here. An absolute name would
	// be one an extractor is free to take literally.
	relative := make([]pkgEntry, len(files))
	for i, f := range files {
		f.name = strings.TrimPrefix(f.name, "/")
		relative[i] = f
	}

	// The metadata comes first and the payload after it, the order a package
	// manager reads the archive in. The listing travels compressed, and the
	// archive carries the directories the files live in: pacman takes away only
	// what the archive and the listing name, so a removal cannot leave one.
	mtree, err := gzipBytes(pacmanMtree(relative))
	if err != nil {
		return err
	}
	entries := []pkgEntry{
		{name: ".PKGINFO", mode: 0o644, data: pacmanPkgInfo(rel.pacman(), arch, repo, relative)},
		{name: ".INSTALL", mode: 0o644, data: []byte(pacmanInstall)},
		{name: ".MTREE", mode: 0o644, data: mtree},
	}
	data, err := tarPack(append(entries, relative...), c)
	if err != nil {
		return err
	}
	name := fmt.Sprintf("%s-%s-%s-%s.pkg.%s", pkgName, rel.pacman(), pkgRelease, arch, c.ext())
	return writePackage(root, name, data)
}

// pacmanPkgInfo is what a package says about itself, in the field of a paragraph
// each. pacman reads it out of the archive to know what it is looking at, and it
// wants the size in bytes: a size in KiB shows up as a package of a few kilobytes.
func pacmanPkgInfo(version, arch, repo string, files []pkgEntry) []byte {
	var b strings.Builder
	fmt.Fprintf(&b, "# Generated by the build task of SDAutoLogin\n")
	fmt.Fprintf(&b, "pkgname = %s\n", pkgName)
	fmt.Fprintf(&b, "pkgbase = %s\n", pkgName)
	fmt.Fprintf(&b, "pkgver = %s-%s\n", version, pkgRelease)
	fmt.Fprintf(&b, "pkgdesc = %s\n", pkgSummary)
	fmt.Fprintf(&b, "url = %s\n", repo)
	fmt.Fprintf(&b, "builddate = %d\n", pkgEpoch.Unix())
	fmt.Fprintf(&b, "packager = %s\n", pkgMaintainer)
	fmt.Fprintf(&b, "size = %d\n", installedBytes(files))
	fmt.Fprintf(&b, "arch = %s\n", arch)
	fmt.Fprintf(&b, "license = MIT\n")
	return []byte(b.String())
}

// pacmanMtree is the listing of every file with its digests, the one an
// installed system is checked against afterwards ("pacman -Qkk"). Each file
// gets a line with the keywords the format uses, the leading directories first.
func pacmanMtree(files []pkgEntry) []byte {
	var listing strings.Builder
	listing.WriteString("#mtree\n/set type=file uid=0 gid=0 mode=644\n")

	seen := map[string]bool{}
	for _, f := range files {
		if f.dir {
			continue
		}
		// The directories carry their own type and mode, since the ones the
		// header above sets are those of a file: a directory named with mode
		// 644 would be one pacman reports as changed.
		for _, d := range parentDirs(f.name) {
			if seen[d] {
				continue
			}
			seen[d] = true
			fmt.Fprintf(&listing, "./%s mode=755 time=%d.0 type=dir\n",
				strings.TrimSuffix(d, "/"), pkgEpoch.Unix())
		}
		fmt.Fprintf(&listing, "./%s mode=%o time=%d.0 size=%d md5digest=%s sha256digest=%s\n",
			f.name, f.mode, pkgEpoch.Unix(), len(f.data), md5Hex(f.data), sha256Hex(f.data))
	}
	return []byte(listing.String())
}

// pacmanInstall is the file pacman reads the functions to run from: the same work
// the scriptlets of the other formats do. The functions are called by name, and
// the ones that are not there are not called.
const pacmanInstall = `# The user the service runs as comes from the file this package installs, which
# nothing reads on its own: the trigger systemd ships only covers its own users.
post_install() {
	if [ -x /usr/bin/systemd-sysusers ]; then
		systemd-sysusers /usr/lib/sysusers.d/sdautologin.conf >/dev/null 2>&1 || :
	fi
	systemctl --system daemon-reload >/dev/null 2>&1 || :
	systemctl --no-reload preset sdautologin.service >/dev/null 2>&1 || :
	if [ ! -f /var/lib/sdautologin/config.json ]; then
		echo "sdautologin has no account yet, so the service will keep stopping."
		echo "See /usr/share/doc/sdautologin/README.md for how to give it one."
	fi
}

post_upgrade() {
	post_install
}

pre_remove() {
	systemctl --no-reload disable --now sdautologin.service >/dev/null 2>&1 || :
}

post_remove() {
	systemctl daemon-reload >/dev/null 2>&1 || :
}
`

func pacmanArch(goarch string) string {
	switch goarch {
	case "amd64":
		return "x86_64"
	case "arm64":
		return "aarch64"
	}
	return goarch
}
